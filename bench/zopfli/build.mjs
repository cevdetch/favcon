// Rebuild only: normal installation needs neither clang nor this sysroot.
// Usage: node bench/zopfli/build.mjs /path/to/source.tar.gz /path/to/sysroot.tar.gz
// clang23.1.4 and wasm-ld on PATH. Archives are pinned before extraction below.
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { benchmarkPath } from '../path.mjs';

const revision = 'ae43a8b73827577c4b19b005b6eed81f5cf9bbac';
const archives = [
  { path: benchmarkPath(process.argv[2]), sha: '9c2fe109838ce43ec90e88ae4a74473c4c46667e32a2980eeb62a04aa1748829' },
  { path: benchmarkPath(process.argv[3]), sha: '9d813544eeebe38b7b8f2244ed591de46b6db812c6dd1a257ff9f0d2a905a2be' },
];
const hash = (bytes) => createHash('sha256').update(bytes).digest('hex');
for (const { path, sha } of archives) {
  if (!path || hash(readFileSync(path)) !== sha) throw new Error(`Missing or incorrect source/sysroot archive: ${path}`);
}
if (!/^clang version 23\.1\.4\b/.test(execFileSync('clang', ['--version'], { encoding: 'utf8' }))) {
  throw new Error('Reproducible build requires clang23.1.4');
}
if (!/^LLD 23\.1\.4\b/.test(execFileSync('wasm-ld', ['--version'], { encoding: 'utf8' }))) {
  throw new Error('Reproducible build requires wasm-ld23.1.4');
}
const scratch = mkdtempSync(join(tmpdir(), 'favseed-zopfli-build.'));
try {
  for (const { path } of archives) execFileSync('tar', ['-xzf', path, '-C', scratch]);
  const source = join(scratch, `zopfli-${revision}`, 'src/zopfli');
  const wrapper = fileURLToPath(new URL('./wrapper.c', import.meta.url));
  const noio = fileURLToPath(new URL('./noio.h', import.meta.url));
  const output = fileURLToPath(new URL('../../lib/zopfli.wasm', import.meta.url));
  const sources = readdirSync(source).filter((name) => name.endsWith('.c') && !name.endsWith('_bin.c')).sort();
  execFileSync('clang', ['--target=wasm32-wasip1', `--sysroot=${join(scratch, 'wasi-sysroot-34.0')}`,
    '-O3', '-flto', '-DNDEBUG', '-msimd128', '-mexec-model=reactor', '-nostartfiles', '-nodefaultlibs',
    '-include', noio, '-Wl,--no-entry', '-Wl,--export-memory', '-Wl,--strip-all',
    ...['allocate', 'deallocate', 'compress_zlib', 'result_size', 'clear_result'].map((name) => `-Wl,--export=${name}`),
    '-Wl,-z,stack-size=1048576', '-Wl,--initial-memory=2097152', `-I${source}`,
    wrapper, ...sources.map((name) => join(source, name)), '-lc', '-lm', '-o', output], { stdio: 'inherit' });
  const sha = hash(readFileSync(output));
  writeFileSync(new URL('../../lib/zopfli-build.mjs', import.meta.url),
    `// Generated by bench/zopfli/build.mjs; rebuild when source, flags or toolchain changes.\n` +
    `export const ZOPFLI_VERSION = '1.0.15+wasm.${sha}';\n`);
  console.log(`Zopfli ${revision}: ${sha}`);
} finally {
  rmSync(scratch, { recursive: true, force: true });
}
